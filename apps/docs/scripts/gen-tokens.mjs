// Generates lib/tokens.generated.ts from the theme package, so the token gallery
// cannot drift from the tokens it documents.
//
// tokens.mdx tells readers "the values below come from @plainconceptsplatform/ui-theme".
// That was not true: showcase.tsx hardcoded every hex as a JS literal. This makes it true.
//
// Colour ramps and semantic slots come from packages/theme/src/theme.css (the stated
// source of truth). The type scale comes from the ai/DESIGN.md frontmatter, which is
// where the Figma-derived typography actually lives.
//
// Runs on predev / prebuild. Output is committed and CI asserts regenerating is a no-op.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");
const themeCss = readFileSync(resolve(repoRoot, "packages/theme/src/theme.css"), "utf8");
const designMd = readFileSync(resolve(repoRoot, "ai/DESIGN.md"), "utf8");
const outFile = resolve(here, "../lib/tokens.generated.ts");

/** Grab a top-level CSS block body by selector. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start === -1) throw new Error(`[gen-tokens] no "${selector}" block in theme.css`);
  let depth = 0;
  for (let i = css.indexOf("{", start); i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") {
      depth--;
      if (depth === 0) return css.slice(css.indexOf("{", start) + 1, i);
    }
  }
  throw new Error(`[gen-tokens] unterminated "${selector}" block`);
}

const rootBlock = block(themeCss, ":root");
const darkBlock = block(themeCss, ".dark");

// --- primitive ramps: --pc-<family>-<step>: <hex> --------------------------
const ramps = new Map();
for (const [, family, step, hex] of rootBlock.matchAll(
  /--pc-([a-z]+)-(\d+):\s*(#[0-9a-fA-F]{3,8})\s*;/g,
)) {
  if (!ramps.has(family)) ramps.set(family, []);
  ramps.get(family).push({ step, hex: hex.toLowerCase() });
}
if (ramps.size === 0) throw new Error("[gen-tokens] found no --pc-* primitives");

// --- semantic slots: resolve var(--pc-*) chains to a literal hex -----------
const primitiveByName = new Map();
for (const [, name, hex] of rootBlock.matchAll(/(--pc-[a-z]+-\d+):\s*(#[0-9a-fA-F]{3,8})\s*;/g)) {
  primitiveByName.set(name, hex.toLowerCase());
}

function semanticSlots(cssBlock) {
  const slots = [];
  for (const [, name, raw] of cssBlock.matchAll(
    /(--(?!pc-)[a-z0-9-]+):\s*(var\(--pc-[a-z0-9-]+\)|#[0-9a-fA-F]{3,8})\s*;/g,
  )) {
    const ref = raw.startsWith("var(") ? raw.slice(4, -1) : null;
    const hex = ref ? primitiveByName.get(ref) : raw.toLowerCase();
    if (!hex) continue; // a var() we cannot resolve locally; skip rather than emit a lie
    slots.push({ token: name, hex, ref });
  }
  return slots;
}

// --- type scale from ai/DESIGN.md frontmatter -----------------------------
const typeScale = [
  ...designMd.matchAll(
    /^ {4}([a-z0-9-]+):\s*\{\s*weight:\s*(\d+),\s*size:\s*(\d+)px,\s*lineHeight:\s*(\d+)px\s*\}/gm,
  ),
].map(([, name, weight, size, lineHeight]) => ({
  name,
  weight: Number(weight),
  size: Number(size),
  lineHeight: Number(lineHeight),
}));
if (typeScale.length === 0)
  throw new Error("[gen-tokens] no type scale in ai/DESIGN.md frontmatter");

const fontFamily = designMd.match(/^ {2}family:\s*(.+)$/m)?.[1]?.trim() ?? "Outfit";
const radius = rootBlock.match(/--radius:\s*([^;]+);/)?.[1]?.trim() ?? null;

const themeVersion = JSON.parse(
  readFileSync(resolve(repoRoot, "packages/theme/package.json"), "utf8"),
).version;

const payload = {
  ramps: Object.fromEntries(
    [...ramps.entries()].map(([family, steps]) => [
      family,
      steps.sort((a, b) => Number(a.step) - Number(b.step)),
    ]),
  ),
  semantic: { light: semanticSlots(rootBlock), dark: semanticSlots(darkBlock) },
  typography: { family: fontFamily, scale: typeScale },
  radius,
};

writeFileSync(
  outFile,
  `// GENERATED by scripts/gen-tokens.mjs from packages/theme/src/theme.css and ai/DESIGN.md.
// Do not edit. Run \`pnpm --filter @plainconceptsplatform/docs gen:tokens\` instead.

export type Swatch = { step: string; hex: string };
export type SemanticSlot = { token: string; hex: string; ref: string | null };
export type TypeStep = { name: string; weight: number; size: number; lineHeight: number };

/** Published version of @plainconceptsplatform/ui-theme, shown in the site nav. */
export const themeVersion = ${JSON.stringify(themeVersion)};

export const tokens = ${JSON.stringify(payload, null, 2)} as {
  ramps: Record<string, Swatch[]>;
  semantic: { light: SemanticSlot[]; dark: SemanticSlot[] };
  typography: { family: string; scale: TypeStep[] };
  radius: string | null;
};
`,
);

const rampCount = Object.keys(payload.ramps).length;
console.log(
  `[gen-tokens] ${rampCount} ramps, ${payload.semantic.light.length} light / ${payload.semantic.dark.length} dark slots, ${typeScale.length} type steps`,
);
